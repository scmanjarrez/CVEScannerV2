-- Static checks of the image packaging. Docker is not needed: the NSE
-- defaults, docker/Dockerfile and .dockerignore must agree.

local t = require 'harness'

local NSE = 'nmap/src/cvescannerv2.nse'
local DOCKERFILE = 'docker/Dockerfile'
local DOCKERIGNORE = '.dockerignore'
local DOWNLOAD_SCRIPT = 'scripts/download-catalog.sh'

-- Files written by the database-builder and catalog-fetcher stages.
local GENERATED = {
  ['cve.db'] = true,
  ['index.json'] = true,
  ['fingerprints.json'] = true,
  ['paths.json'] = true,
  ['probes.json'] = true,
}

local function read_file(path)
  local file = assert(io.open(path, 'r'),
    'Run the tests from the repository root: cannot open ' .. path)
  local body = file:read('*all')
  file:close()
  return body
end

local function lines_of(body)
  local lines = {}
  for line in (body .. '\n'):gmatch('(.-)\n') do
    table.insert(lines, line)
  end
  return lines
end

-- Lines of Lua code, without the comment lines.
local function code_lines(body)
  local code = {}
  for _, line in ipairs(lines_of(body)) do
    if not line:match('^%s*%-%-') then table.insert(code, line) end
  end
  return code
end

-- Data file names that the NSE code reads from the data directory.
local function referenced_data_files(body)
  local patterns = {
    "'data/([%w%._%-]+)'",
    "read_catalog_json%('([%w%._%-]+)'%)",
    "= '([%w%._%-]+%.json)'",
  }
  local names = {}
  for _, line in ipairs(code_lines(body)) do
    for _, pattern in ipairs(patterns) do
      for name in line:gmatch(pattern) do names[name] = true end
    end
  end
  return names
end

-- Names copied from the repository by COPY instructions ('data/<x>').
local function copied_data_files(dockerfile)
  local names = {}
  for _, line in ipairs(lines_of(dockerfile)) do
    if line:match('^COPY%s') then
      for token in line:gmatch('%S+') do
        local name = token:match('^data/([%w%._%-]+)$')
        if name then names[name] = true end
      end
    end
  end
  return names
end

local function sorted_keys(set)
  local keys = {}
  for key in pairs(set) do table.insert(keys, key) end
  table.sort(keys)
  return keys
end

local function index_of(lines, value)
  for i, line in ipairs(lines) do
    if line == value then return i end
  end
  return nil
end

local function read_scanner_sources()
  local parts = { read_file(NSE) }
  local pipe = io.popen(
    "find nmap/src/cvescannerv2 -name '*.lua' | sort 2>/dev/null")
  if pipe then
    for path in pipe:lines() do
      table.insert(parts, read_file(path))
    end
    pipe:close()
  end
  return table.concat(parts, '\n')
end

local nse = read_scanner_sources()
local dockerfile = read_file(DOCKERFILE)
local dockerignore = {}
for _, line in ipairs(lines_of(read_file(DOCKERIGNORE))) do
  table.insert(dockerignore, (line:gsub('%s+$', '')))
end
local referenced = referenced_data_files(nse)
local copied = copied_data_files(dockerfile)

t.suite('docker packaging')

t.case('NSE data defaults are discovered from the code', function()
  t.truthy(referenced['cve.db'], 'data/cve.db default not found')
  t.truthy(referenced['product-aliases.json'], 'aliases default not found')
  t.truthy(referenced['index.json'], 'catalogue index not found')
end)

t.case('every NSE data default is copied or generated by the image', function()
  local missing = {}
  for _, name in ipairs(sorted_keys(referenced)) do
    if not (GENERATED[name] or copied[name]) then
      table.insert(missing, name)
    end
  end
  t.eq(missing, {}, 'NSE reads data files that the Dockerfile does not ship')
end)

t.case('generated stages write the files listed as generated', function()
  local expected = {
    'COPY --link --from=database-builder /output/cve.db /CVEScannerV2/data/cve.db',
    'COPY --link --from=catalog-fetcher /catalog/ /CVEScannerV2/data/',
  }
  for _, text in ipairs(expected) do
    t.truthy(dockerfile:find(text, 1, true), 'missing in Dockerfile: ' .. text)
  end
end)

t.case('COPY data sources exist in the repository', function()
  local missing = {}
  for _, name in ipairs(sorted_keys(copied)) do
    local file = io.open('data/' .. name, 'r')
    if file then file:close() else table.insert(missing, name) end
  end
  t.eq(missing, {}, 'COPY sources missing from data/')
end)

t.case('COPY data sources are re-included by .dockerignore', function()
  local blanket = index_of(dockerignore, 'data/*')
  local root = index_of(dockerignore, '**')
  local excluded = {}
  for _, name in ipairs(sorted_keys(copied)) do
    local re = index_of(dockerignore, '!data/' .. name)
    if not re then
      table.insert(excluded, name .. ' (no !data/ rule)')
    elseif (blanket and blanket > re) or (root and root > re) then
      table.insert(excluded, name .. ' (rule before the exclusion)')
    end
  end
  t.eq(excluded, {}, '.dockerignore excludes COPY sources')
end)

t.case('download script base equals Dockerfile CATALOG_BASE', function()
  local file = io.open(DOWNLOAD_SCRIPT, 'r')
  t.truthy(file, DOWNLOAD_SCRIPT .. ' not found (created by TASK-16)')
  local body = file and file:read('*all') or ''
  if file then file:close() end
  local script_base = body:match(
    "(https://raw%.githubusercontent%.com/[^%s'\"}]+/)")
  local docker_base = dockerfile:match('ARG CATALOG_BASE=(%S+)')
  t.truthy(script_base, 'default catalogue base not found in the script')
  t.eq(docker_base, script_base, 'CATALOG_BASE differs from the script')
end)
